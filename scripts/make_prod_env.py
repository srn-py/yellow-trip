# scripts/make_prod_env.py
"""Create `.env.prod`: the production settings, with strong random secrets.

Run it once per server (or once for a local rehearsal):

    python scripts/make_prod_env.py --domain taxi.example.com --email you@example.com --owner your-github-name
    python scripts/make_prod_env.py --local

Why a script? People choose weak passwords and reuse them. Random secrets of sensible length, generated
on the machine that will use them and never committed, are the cheapest security improvement there is.

The dashboard/Airflow/ingest login is stored only as a bcrypt hash. The hash is produced by Caddy's own
tool through Docker, so Docker must be running. The plain password is printed once; save it.
"""

import argparse
import secrets
import subprocess
from collections.abc import Callable
from pathlib import Path

CADDY_IMAGE = "caddy:2"


def random_secret(length_bytes: int = 24) -> str:
    """Create a random URL-safe secret.

    Args:
        length_bytes: Randomness in bytes (the text is about 1.3 times longer).

    Returns:
        A string of letters, digits, '-' and '_'.
    """
    return secrets.token_urlsafe(length_bytes)


def hash_with_caddy(password: str) -> str:
    """Hash a password with Caddy's own tool (needs Docker).

    Args:
        password: The plain password.

    Returns:
        A bcrypt hash that Caddy accepts for basic authentication.

    Raises:
        SystemExit: If Docker cannot run the tool.
    """
    command = ["docker", "run", "--rm", CADDY_IMAGE, "caddy", "hash-password", "--plaintext", password]
    try:
        result = subprocess.run(command, capture_output=True, text=True, check=True, timeout=300)
    except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
        raise SystemExit(f"Could not hash the password with Docker ({exc}). Is Docker running?") from exc
    return result.stdout.strip()


def build_env_text(
    *,
    domain: str,
    email: str,
    owner: str,
    tag: str,
    local: bool,
    ops_user: str,
    ops_password: str,
    hash_password: Callable[[str], str] = hash_with_caddy,
    rand: Callable[[], str] = random_secret,
) -> str:
    """Build the content of `.env.prod`.

    Args:
        domain: The domain the platform is served on (`localhost` for a rehearsal).
        email: Contact address for Let's Encrypt.
        owner: GitHub user or organisation that owns the images (lowercase).
        tag: Image tag to run, for example "1.0.0" or "latest".
        local: True for a rehearsal on your own computer (local certificates, high ports, local images).
        ops_user: Login name for the dashboard, Airflow and the ingest API.
        ops_password: The plain login password (only its hash is stored).
        hash_password: Function that hashes a password for Caddy. Replaced in tests.
        rand: Function that returns a new random secret. Replaced in tests.

    Returns:
        The file content.
    """
    https_port = 8443 if local else 443
    port_suffix = "" if https_port == 443 else f":{https_port}"
    caddyfile = "Caddyfile.local" if local else "Caddyfile"
    jwt_secret = rand() + rand()  # Airflow wants a long signing key
    return f"""# .env.prod - PRODUCTION SETTINGS AND SECRETS. Never commit this file. Keep it readable only by you (chmod 600).
# Generated by scripts/make_prod_env.py. To rotate a secret: change it here, then run ./deploy/prod.sh up -d
# (database passwords also need changing inside the database; see docs/deployment.md).

# --- Where it lives ---
SITE_DOMAIN={domain}
ACME_EMAIL={email}
CADDYFILE={caddyfile}
HTTP_PORT={8088 if local else 80}
HTTPS_PORT={https_port}

# --- Which version to run ---
GHCR_OWNER={owner}
IMAGE_TAG={tag}

# --- Behaviour ---
LOG_LEVEL=INFO
PIPELINE_MONTH_LAG=2
DUCKDB_MEMORY_LIMIT=2GB
QUALITY_INTERVAL_SECONDS=300

# --- Secrets ---
S3_ACCESS_KEY={rand()}
S3_SECRET_KEY={rand()}
POSTGRES_DB=taxi_dw
POSTGRES_USER=taxi
POSTGRES_PASSWORD={rand()}
AIRFLOW_DB_PASSWORD={rand()}
AIRFLOW_JWT_SECRET={jwt_secret}
GRAFANA_ADMIN_PASSWORD={rand()}
GRAFANA_ROOT_URL=https://grafana.{domain}{port_suffix}

# --- Login for the dashboard, Airflow and the ingest API (a bcrypt hash, in single quotes because of the $) ---
OPS_USER={ops_user}
OPS_PASSWORD_HASH='{hash_password(ops_password)}'

# --- Alerts: any URL that accepts a JSON POST (empty = alerts are only visible in Grafana and Prometheus) ---
ALERT_WEBHOOK_URL=
"""


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point.

    Args:
        argv: Command-line arguments (default: the real ones).

    Returns:
        The exit code.
    """
    parser = argparse.ArgumentParser(description="Create .env.prod with strong random secrets.")
    parser.add_argument("--domain", help="Domain name, for example taxi.example.com")
    parser.add_argument("--email", help="Contact address for Let's Encrypt")
    parser.add_argument("--owner", help="GitHub user or organisation that owns the images (lowercase)")
    parser.add_argument("--tag", help="Image tag to run (default: latest, or local for --local)")
    parser.add_argument("--local", action="store_true", help="A rehearsal on this computer")
    parser.add_argument("--ops-user", default="ops", help="Login name (default: ops)")
    parser.add_argument("--ops-password", help="Login password (default: a random one, printed once)")
    parser.add_argument("--output", default=".env.prod", help="File to write (default: .env.prod)")
    parser.add_argument("--force", action="store_true", help="Overwrite an existing file")
    args = parser.parse_args(argv)

    if not args.local and not (args.domain and args.email and args.owner):
        parser.error("--domain, --email and --owner are required (or use --local)")

    output = Path(args.output)
    if output.exists() and not args.force:
        parser.error(f"{output} already exists. Use --force to replace it (this changes every secret).")

    generated_password = args.ops_password is None
    password = args.ops_password or random_secret(12)
    text = build_env_text(
        domain="localhost" if args.local else args.domain,
        email="" if args.local else args.email,
        owner="local" if args.local else args.owner.lower(),
        tag=args.tag or ("local" if args.local else "latest"),
        local=args.local,
        ops_user=args.ops_user,
        ops_password=password,
        hash_password=hash_with_caddy,
    )
    output.write_text(text, encoding="utf-8")
    try:
        output.chmod(0o600)  # readable by you only (has no effect on Windows)
    except OSError:
        pass

    print(f"Wrote {output}")
    if generated_password:
        print(f"Login for the dashboard, Airflow and the ingest API:  {args.ops_user} / {password}")
        print("Save this password now. Only its hash is stored in the file.")
    print("Next: ./deploy/prod.sh up -d" + (" --build" if args.local else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())