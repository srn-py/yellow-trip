# services/ingestion/ingestion_service/registry.py
"""The file registry: our permanent record of every file we ingested.

Why a registry?
- **No duplicates:** the checksum tells us if we already have this exact content.
- **Audit trail:** where did each file come from, when, how big, how many rows?
- **Skip work:** if "2024-01" is already ingested, do not download it again.

It uses SQLite, a database that lives in a single file and ships with Python.
Only the ingestion service reads/writes it; other services will ask the
ingestion API (`GET /files`) rather than opening this file.
"""

import sqlite3
from collections.abc import Iterator
from contextlib import contextmanager
from datetime import UTC, datetime
from pathlib import Path

_SCHEMA = """
CREATE TABLE IF NOT EXISTS ingested_files (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    sha256      TEXT NOT NULL UNIQUE,   -- content fingerprint: UNIQUE blocks duplicates
    filename    TEXT NOT NULL,
    dataset     TEXT NOT NULL,          -- yellow_tripdata | taxi_zone_lookup | uploads
    file_format TEXT NOT NULL,          -- parquet | csv | ndjson
    source      TEXT NOT NULL,          -- tlc_download | upload | dropzone
    bucket      TEXT NOT NULL,
    object_key  TEXT NOT NULL,
    size_bytes  INTEGER NOT NULL,
    row_count   INTEGER,
    year        INTEGER,                -- only for trip data
    month       INTEGER,                -- only for trip data
    ingested_at TEXT NOT NULL           -- UTC timestamp, ISO format
);
"""

# Columns we write on insert (id is generated by the database).
_INSERT_COLUMNS = (
    "sha256",
    "filename",
    "dataset",
    "file_format",
    "source",
    "bucket",
    "object_key",
    "size_bytes",
    "row_count",
    "year",
    "month",
    "ingested_at",
)


class FileRegistry:
    """Read/write access to the `ingested_files` table."""

    def __init__(self, db_path: str):
        self._db_path = Path(db_path)
        self._db_path.parent.mkdir(parents=True, exist_ok=True)
        with self._connection() as conn:
            conn.execute(_SCHEMA)

    @contextmanager
    def _connection(self) -> Iterator[sqlite3.Connection]:
        """Open a connection that commits on success and always closes."""
        conn = sqlite3.connect(self._db_path)
        conn.row_factory = sqlite3.Row  # rows behave like dicts
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()

    def find_by_checksum(self, sha256: str) -> dict | None:
        """Find a file by its content fingerprint.

        Args:
            sha256: Checksum of the file.

        Returns:
            The registry record, or None if this content was never ingested.
        """
        with self._connection() as conn:
            row = conn.execute("SELECT * FROM ingested_files WHERE sha256 = ?", (sha256,)).fetchone()
        return dict(row) if row else None

    def find_by_period(self, dataset: str, year: int, month: int) -> dict | None:
        """Find the latest file registered for a dataset and month.

        Args:
            dataset: Dataset name, e.g. "yellow_tripdata".
            year: Four-digit year.
            month: Month number 1 to 12.

        Returns:
            The registry record, or None.
        """
        with self._connection() as conn:
            row = conn.execute(
                "SELECT * FROM ingested_files WHERE dataset = ? AND year = ? AND month = ? ORDER BY id DESC LIMIT 1",
                (dataset, year, month),
            ).fetchone()
        return dict(row) if row else None

    def add(self, record: dict) -> dict:
        """Insert a new record.

        Args:
            record: Values for the columns (see `_INSERT_COLUMNS`); `ingested_at`
                is filled in automatically.

        Returns:
            The stored record including its new `id`.
        """
        values = {column: record.get(column) for column in _INSERT_COLUMNS}
        values["ingested_at"] = datetime.now(UTC).isoformat(timespec="seconds")
        columns = ", ".join(_INSERT_COLUMNS)
        placeholders = ", ".join(f":{column}" for column in _INSERT_COLUMNS)
        # Column names come from the constant above, never from user input,
        # and the VALUES use bound parameters, so this is safe from SQL injection.
        with self._connection() as conn:
            cursor = conn.execute(f"INSERT INTO ingested_files ({columns}) VALUES ({placeholders})", values)
            row = conn.execute("SELECT * FROM ingested_files WHERE id = ?", (cursor.lastrowid,)).fetchone()
        return dict(row)

    def list_files(self, dataset: str | None = None, limit: int = 100) -> list[dict]:
        """List registered files, newest first.

        Args:
            dataset: Optional filter by dataset name.
            limit: Maximum number of records.

        Returns:
            A list of records.
        """
        query = "SELECT * FROM ingested_files"
        params: list = []
        if dataset:
            query += " WHERE dataset = ?"
            params.append(dataset)
        query += " ORDER BY id DESC LIMIT ?"
        params.append(limit)
        with self._connection() as conn:
            rows = conn.execute(query, params).fetchall()
        return [dict(row) for row in rows]
